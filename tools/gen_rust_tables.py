"""Generate rust/src/tables.rs from the Python engine's data (awbw/data.py, awbw/cos.py).

    py -3.12 tools/gen_rust_tables.py

Run it whenever data.py or a CO's constants change, then rebuild the Rust engine. Only constants are generated;
the rules themselves live in rust/src/game.rs and mirror awbw/game.py + awbw/cos.py function by function.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from awbw import data as D            # noqa: E402
from awbw.cos import COS              # noqa: E402

UT, TK, MT = D.UT, D.TK, D.MT
NU, NT, NM = len(UT), len(TK), len(MT)
WEATHERS = ["C", "R", "S"]


def arr(vals, ty):
    return f"[{', '.join(str(v) for v in vals)}]"


def boolarr(s, n):
    return arr(["true" if i in s else "false" for i in range(n)], "bool")


out = ["// GENERATED by tools/gen_rust_tables.py from awbw/data.py and awbw/cos.py - do not edit by hand.",
       "#![allow(dead_code)]", ""]
out.append(f"pub const NU: usize = {NU};\npub const NT: usize = {NT};\npub const NM: usize = {NM};")
for e, prefix in ((UT, "UT"), (TK, "TK"), (MT, "MT")):
    for m in e:
        out.append(f"pub const {prefix}_{m.name}: u8 = {int(m)};")
U = [D.UNITS[UT(i)] for i in range(NU)]
out.append(f"pub const UNIT_NAME: [&str; NU] = [{', '.join(repr(u.name).replace(chr(39), chr(34)) for u in U)}];")
for f in ("mp", "ammo", "fuel", "fuel_per_turn", "rmin", "rmax", "cost", "hidden_fuel"):
    out.append(f"pub const UNIT_{f.upper()}: [i64; NU] = {arr([getattr(u, f) for u in U], 'i64')};")
out.append(f"pub const UNIT_MT: [u8; NU] = {arr([int(u.mt) for u in U], 'u8')};")
out.append(f"pub const DMG: [[i64; NU]; NU] = [{', '.join(arr(r, 'i64') for r in D.DMG)}];")
out.append(f"pub const MG_DMG: [[i64; NU]; NU] = [{', '.join(arr(r, 'i64') for r in D.MG_DMG)}];")
out.append(f"pub const USES_AMMO: [[bool; NU]; NU] = [{', '.join(arr(['true' if D.uses_ammo(UT(a), UT(d)) else 'false' for d in range(NU)], 'b') for a in range(NU))}];")
out.append(f"pub const STARS: [i64; NT] = {arr([D.STARS[TK(i)] for i in range(NT)], 'i64')};")
mc = []
for w in WEATHERS:
    rows = []
    for t in range(NT):
        rows.append(arr([D.move_cost(w, TK(t), MT(m)) if D.move_cost(w, TK(t), MT(m)) is not None else -1 for m in range(NM)], "i64"))
    mc.append(f"[{', '.join(rows)}]")
out.append(f"/// [weather C,R,S][terrain][movement type], -1 = impassable\npub const MOVE_COST: [[[i64; NM]; NT]; 3] = [{', '.join(mc)}];")
for name, s in (("FOOT", D.FOOT), ("AIR", D.AIR_UNITS), ("NAVAL", D.NAVAL_UNITS), ("LAND_INDIRECT", D.LAND_INDIRECT),
                ("VEHICLE", D.VEHICLES), ("GROUND", D.GROUND_UNITS), ("TRANSPORT", D.TRANSPORTS)):
    out.append(f"pub const IS_{name}: [bool; NU] = {boolarr({int(u) for u in s}, NU)};")
for name, s in (("CAPTURABLE", D.CAPTURABLE), ("INCOME", D.INCOME_PROPS), ("URBAN", D.URBAN)):
    out.append(f"pub const IS_{name}: [bool; NT] = {boolarr({int(t) for t in s}, NT)};")
cap = [D.CARRY.get(UT(i), (0, frozenset()))[0] for i in range(NU)]
can = [[UT(c) in D.CARRY.get(UT(t), (0, frozenset()))[1] for c in range(NU)] for t in range(NU)]
out.append(f"pub const CARRY_CAP: [usize; NU] = {arr(cap, 'usize')};")
out.append(f"pub const CARRIES: [[bool; NU]; NU] = [{', '.join(arr(['true' if x else 'false' for x in r], 'b') for r in can)}];")
for k, name in ((TK.BASE, "FACTORY"), (TK.AIRPORT, "AIRPORT"), (TK.PORT, "PORT")):
    menu = [int(u) for u in D.BUILDS[k]]
    out.append(f"pub const BUILD_{name}: [u8; {len(menu)}] = {arr(menu, 'u8')};")
names = list(COS)
cos = [COS[n] for n in names]
out.append(f"pub const NCO: usize = {len(cos)};")
out.append(f"pub const CO_NAME: [&str; NCO] = [{', '.join(chr(34) + n + chr(34) for n in names)}];")
for i, n in enumerate(names):
    out.append(f"pub const CO_{n.upper().replace(' ', '_')}: u8 = {i};")
out.append(f"pub const CO_COP_STARS: [i64; NCO] = {arr([c.cop_stars for c in cos], 'i64')};")
out.append(f"pub const CO_SCOP_STARS: [i64; NCO] = {arr([c.scop_stars for c in cos], 'i64')};")
out.append(f"pub const CO_HAS_COP: [bool; NCO] = {arr(['true' if c.has_cop else 'false' for c in cos], 'b')};")
out.append(f"pub const CO_LUCK: [[(i64, i64); 3]; NCO] = [{', '.join('[' + ', '.join(f'({a}, {b})' for a, b in c.luck_levels) + ']' for c in cos)}];")
out.append(f"pub const CO_COST_PCT: [[i64; 3]; NCO] = [{', '.join(arr(c.cost_levels, 'i64') for c in cos)}];")
out.append(f"pub const CO_REPAIR_BONUS: [i64; NCO] = {arr([c.repair_bonus for c in cos], 'i64')};")
out.append(f"pub const CO_FLAT_MOVE: [[bool; 3]; NCO] = [{', '.join(arr(['true' if x else 'false' for x in c.flat_move_cost_levels], 'b') for c in cos)}];")
dst = ROOT / "rust" / "src" / "tables.rs"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text("\n".join(out) + "\n")
print("wrote", dst, len(out), "lines")
